const TOOL_BY_ID = new Map(ASSISTANT_TOOL_CAPABILITIES.map((t) => [t.toolId, t]));

export function getAssistantToolCapability(toolId: string): AssistantToolCapability | null {
  return TOOL_BY_ID.get(toolId) ?? null;
}

export function listAssistantToolsByCategory(category: AssistantToolCapability["category"]): AssistantToolCapability[] {
  return ASSISTANT_TOOL_CAPABILITIES.filter((t) => t.category === category);
}

export function listAssistantToolsForAsset(assetType: string): AssistantToolCapability[] {
  return ASSISTANT_TOOL_CAPABILITIES.filter(
    (t) =>
      t.supportedAssetTypes.includes(assetType as AssistantToolCapability["supportedAssetTypes"][number]) ||
      t.supportedAssetTypes.includes("image")
  );
}
