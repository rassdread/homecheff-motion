import { buildAssistantActionRoute } from "@/lib/assistant-route-builder";
import { buildEditorMorphActionRoute } from "@/lib/editor-morph-actions";
import type { AssistantToolCapability } from "@/types/assistant-v4";

function editorRoute(workflow: string, extra?: Record<string, string>): string {
  const params = new URLSearchParams({ workflow, ...extra });
  return `/editor?${params.toString()}`;
}

function morphTool(
  id: import("@/lib/editor-morph-actions").EditorMorphActionId,
  partial: Omit<AssistantToolCapability, "toolId" | "route" | "morphActionId" | "category">
): AssistantToolCapability {
  return {
    toolId: id,
    category: "morph",
    route: buildEditorMorphActionRoute(id),
    morphActionId: id,
    ...partial,
  };
}

